"""Dry-run planning for schema changes.

``sync_engine`` produces a list of DDL strings.  Before running them a user needs
to know what the change *does*, which of it is destructive, and how to review it —
and the caller needs to decide whether the whole thing should run in one
transaction.

Kept separate from the DDL generator so the classification and summary rules can
be tested on their own.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from enum import Enum
from typing import Iterator, Sequence

#: Matches ``/* ... */`` comments, including multi-line ones.
_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)


class StatementKind(str, Enum):
    """How risky a planned statement is."""

    CREATE = "create"
    ALTER = "alter"
    DROP = "drop"
    DATA = "data"


@dataclass(frozen=True)
class PlannedStatement:
    """One statement in a plan, with what a reviewer needs to judge it."""

    sql: str
    kind: StatementKind

    @property
    def is_destructive(self) -> bool:
        """True when running this can lose data.

        DROP always can.  An ALTER can too, and the classifier surfaces a column
        drop as DROP for exactly that reason.
        """
        return self.kind in (StatementKind.DROP, StatementKind.DATA)

    @property
    def needs_confirmation(self) -> bool:
        return self.is_destructive

    @property
    def marker(self) -> str:
        """Prefix used in the review block to draw the eye."""
        return "!! " if self.is_destructive else "   "


def first_keyword(sql: str) -> str:
    """The statement's leading keyword, skipping comments and blank lines.

    A generated script often starts with a ``-- header`` line; reading the raw
    first word would classify the comment instead of the statement.
    """
    # Strip block comments first, then scan line by line so a leading
    # "-- generated by ..." header cannot be mistaken for the statement.
    text = _BLOCK_COMMENT.sub(" ", sql)
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith(("--", "#")):
            continue
        return stripped.split(None, 1)[0].upper()
    return ""


def classify(sql: str) -> StatementKind:
    """Classify a statement by its leading keyword."""
    head = sql.upper()
    keyword = first_keyword(sql)
    if keyword == "DROP":
        return StatementKind.DROP
    if keyword == "TRUNCATE":
        return StatementKind.DROP
    if keyword == "DELETE":
        return StatementKind.DATA
    if keyword in ("ALTER", "RENAME"):
        # ALTER ... DROP COLUMN is destructive despite the ALTER keyword.
        return StatementKind.DROP if " DROP " in head else StatementKind.ALTER
    if keyword in ("CREATE", "INSERT"):
        return StatementKind.CREATE
    return StatementKind.ALTER


@dataclass
class Plan:
    """An ordered set of statements plus the summary a UI needs."""

    statements: list[PlannedStatement] = field(default_factory=list)
    #: False when the engine cannot wrap the change in one transaction (e.g. a
    #: DDL statement on an engine with implicit commits), so the caller can warn
    #: instead of promising atomicity.
    transactional: bool = True

    def __iter__(self) -> Iterator[PlannedStatement]:
        return iter(self.statements)

    def __len__(self) -> int:
        return len(self.statements)

    def __bool__(self) -> bool:
        return bool(self.statements)

    @property
    def destructive_count(self) -> int:
        return sum(1 for s in self.statements if s.is_destructive)

    @property
    def requires_confirmation(self) -> bool:
        return self.destructive_count > 0

    def by_kind(self) -> dict[str, list[PlannedStatement]]:
        """Group statements so a summary view can list them by category."""
        groups: dict[str, list[PlannedStatement]] = {}
        for statement in self.statements:
            groups.setdefault(statement.kind.value, []).append(statement)
        return groups

    def preview_text(self) -> str:
        """The whole plan as one reviewable block.

        Destructive statements are flagged inline so a reviewer's eye lands on
        them before anything runs.
        """
        return "\n".join(s.marker + s.sql.rstrip() for s in self.statements)

    def summary(self) -> str:
        """One-line description, e.g. ``3 statement(s), 2 destructive``."""
        total = len(self.statements)
        if not total:
            return "no changes"
        if self.destructive_count:
            return f"{total} statement(s), {self.destructive_count} destructive"
        return f"{total} statement(s)"


def plan_from_statements(statements: Sequence[str], *, transactional: bool = True) -> Plan:
    """Wrap raw DDL strings in a :class:`Plan`, classifying each one."""
    return Plan(
        statements=[PlannedStatement(sql=s, kind=classify(s)) for s in statements],
        transactional=transactional,
    )
